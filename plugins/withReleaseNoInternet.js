// Expo config plugin: strip android.permission.INTERNET from RELEASE builds only.
//
// Why not `android.blockedPermissions`? That writes tools:node="remove" into the MAIN
// manifest, which applies to every build type — debug builds then cannot reach the
// Metro bundler. A manifest in the `release` source set has higher merge priority than
// main and all libraries, so the removal applies to release only. (06 §3.1, 10 P1)
// SYSTEM_ALERT_WINDOW is also dev-only (React Native's debug error overlay), so release drops it.
const fs = require('fs');
const path = require('path');
const { withDangerousMod } = require('expo/config-plugins');

const RELEASE_MANIFEST_RELATIVE_PATH = path.join('app', 'src', 'release', 'AndroidManifest.xml');

const RELEASE_MANIFEST_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withReleaseNoInternet.js. Do not edit. (TARA 06 §3.1, 10 P1) -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools">
    <uses-permission android:name="android.permission.INTERNET" tools:node="remove" />
    <uses-permission android:name="android.permission.SYSTEM_ALERT_WINDOW" tools:node="remove" />
    <uses-permission-sdk-23 android:name="android.permission.ACCESS_COARSE_LOCATION" tools:node="remove" />
</manifest>
`;

function writeReleaseManifest(androidProjectRoot) {
  const target = path.join(androidProjectRoot, RELEASE_MANIFEST_RELATIVE_PATH);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, RELEASE_MANIFEST_XML, 'utf8');
  return target;
}

function withReleaseNoInternet(config) {
  return withDangerousMod(config, [
    'android',
    (modConfig) => {
      writeReleaseManifest(modConfig.modRequest.platformProjectRoot);
      return modConfig;
    },
  ]);
}

module.exports = withReleaseNoInternet;
module.exports.RELEASE_MANIFEST_XML = RELEASE_MANIFEST_XML;
module.exports.RELEASE_MANIFEST_RELATIVE_PATH = RELEASE_MANIFEST_RELATIVE_PATH;
module.exports.writeReleaseManifest = writeReleaseManifest;
